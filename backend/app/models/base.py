"""Shared building blocks for every model: the declarative Base and a timestamps mixin."""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, Uuid, func
from sqlalchemy.orm import DeclarativeBase, Mapped, MappedColumn, mapped_column

# Give every constraint and index a predictable name, e.g. "uq_states_name".
# Without this, PostgreSQL invents names, and Alembic can't reliably find them later.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Parent class of all models. Its metadata lists all our tables (Alembic reads it)."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def uuid_primary_key() -> MappedColumn[uuid.UUID]:
    """Primary key column used by every table: a UUIDv7 generated by PostgreSQL.

    Why UUIDv7 instead of 1, 2, 3...?
    - Not guessable: nobody can walk through /facilities/1, /2, /3 to scrape records.
    - Leaks nothing: an id doesn't reveal how many rows exist.
    - Time-ordered: it starts with a timestamp, so new rows land at the end of the index,
      keeping inserts nearly as fast as sequential numbers (random ids scatter writes).
    PostgreSQL 18 has a built-in uuidv7() function, so no Python library is needed.
    The id is None in Python until the row is flushed to the database.
    """
    return mapped_column(Uuid, primary_key=True, server_default=func.uuidv7())


class TimestampMixin:
    """Adds created_at / updated_at to any model that inherits it.

    The database fills the values (server_default), so they're correct even for rows
    inserted outside Python. timezone=True stores an absolute moment, avoiding timezone bugs.
    """

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
